function normalizeTags(tags) {
    if (Array.isArray(tags)) {
        return tags.map(tag => String(tag).trim().toLowerCase());
    }

    if (tags && typeof tags === 'object') {
        return Object.values(tags)
            .flat()
            .map(tag => String(tag).trim().toLowerCase());
    }

    return String(tags || '')
        .split(/\s+/)
        .map(tag => tag.trim().toLowerCase())
        .filter(Boolean);
}

function isBlocked(tags) {
    const normalizedTags = normalizeTags(tags);

    return Boolean(
        kenaBlokir(normalizedTags) ||
        normalizedTags.some(tag =>
            BLOCKED_TAGS.has(tag) || AI_GENERATED_TAGS.has(tag)
        )
    );
}

function buildSearchUrl(query) {
    const url = new URL(API_URL);
    url.searchParams.set(
        'tags',
        ['rating:e', query].filter(Boolean).join(' ')
    );
    url.searchParams.set('limit', String(MAX_RESULTS));
    return url;
}

function getProxyAgent() {
    const proxyUrl = String(process.env.RULE34_PROXY_URL || '').trim();
    if (!proxyUrl) {
        return undefined;
    }

    if (proxyAgent && configuredProxyUrl === proxyUrl) {
        return proxyAgent;
    }

    let parsedProxyUrl;
    try {
        parsedProxyUrl = new URL(proxyUrl);
    } catch {
        throw new Error('RULE34_PROXY_URL bukan URL proxy yang valid.');
    }

    if (!['http:', 'https:'].includes(parsedProxyUrl.protocol)) {
        throw new Error(
            'RULE34_PROXY_URL harus menggunakan protokol http:// atau https://.'
        );
    }

    configuredProxyUrl = proxyUrl;
    proxyAgent = new HttpsProxyAgent(parsedProxyUrl);
    return proxyAgent;
}

function getUserAgent() {
    const userAgent = String(
        process.env.E621_USER_AGENT || DEFAULT_USER_AGENT
    ).trim();

    if (!userAgent || /[\r\n]/.test(userAgent)) {
        throw new Error('E621_USER_AGENT harus berupa satu baris yang valid.');
    }

    return userAgent;
}

function getNetworkErrorCode(error) {
    let currentError = error;
    while (currentError) {
        if (currentError.code) {
            return currentError.code;
        }
        currentError = currentError.cause;
    }
    return undefined;
}

function addCertificateGuidance(error) {
    if (getNetworkErrorCode(error) !== 'CERT_HAS_EXPIRED') {
        return error;
    }

    return new Error(
        'Sertifikat TLS yang diterima saat menghubungi e621 sudah kedaluwarsa. ' +
        'Periksa tanggal/jam server, lalu coba jaringan lain atau proxy tepercaya ' +
        'melalui RULE34_PROXY_URL. Verifikasi TLS tetap aktif.',
        { cause: error }
    );
}

function shouldRetryWithDoh(error) {
    return [
        'ENOTFOUND',
        'EAI_AGAIN',
        'ECONNRESET',
        'ETIMEDOUT',
        'ECONNREFUSED',
        'ERR_TLS_CERT_ALTNAME_INVALID',
        'ERR_CERT_AUTHORITY_INVALID'
    ].includes(getNetworkErrorCode(error));
}

async function resolveWithDoh(hostname) {
    const dohUrl = String(
        process.env.RULE34_DOH_URL || DEFAULT_DOH_URL
    ).trim();
    const resolverUrl = new URL(dohUrl);

    if (resolverUrl.protocol !== 'https:') {
        throw new Error('RULE34_DOH_URL harus menggunakan HTTPS.');
    }

    const addresses = [];
    for (const type of ['A', 'AAAA']) {
        resolverUrl.searchParams.set('name', hostname);
        resolverUrl.searchParams.set('type', type);

        const response = await fetch(resolverUrl, {
            headers: { Accept: 'application/dns-json' },
            signal: AbortSignal.timeout(DOH_TIMEOUT_MS)
        });
        if (!response.ok) {
            throw new Error(`Resolver DNS mengembalikan HTTP ${response.status}.`);
        }

        const result = await response.json();
        if (result.Status !== 0) {
            continue;
        }

        for (const answer of result.Answer || []) {
            if (
                answer.type !== 1 &&
                answer.type !== 28
            ) {
                continue;
            }

            const family = answer.type === 1 ? 4 : 6;
            if (net.isIP(answer.data) === family) {
                addresses.push({
                    address: answer.data,
                    family
                });
            }
        }
    }

    if (!addresses.length) {
        throw new Error(`DNS-over-HTTPS tidak menemukan IP untuk ${hostname}.`);
    }

    return addresses;
}

function createDohLookup(addresses) {
    return (_hostname, options, callback) => {
        if (options && options.all) {
            callback(null, addresses);
            return;
        }

        const address = addresses[0];
        callback(null, address.address, address.family);
    };
}

function requestHttpsOnce(url, options, redirectCount, lookup) {
    const targetUrl = new URL(url);
    if (targetUrl.protocol !== 'https:') {
        return Promise.reject(new Error('Hanya HTTPS yang didukung.'));
    }

    return new Promise((resolve, reject) => {
        let settled = false;
        const fail = error => {
            if (!settled) {
                settled = true;
                reject(error);
            }
        };

        const request = https.get(targetUrl, {
            agent: getProxyAgent(),
            ...(lookup ? { lookup } : {}),
            headers: {
                'User-Agent': getUserAgent(),
                ...options.headers
            },
            timeout: options.timeoutMs
        }, response => {
            const statusCode = response.statusCode || 0;
            const location = response.headers.location;

            if (statusCode >= 300 && statusCode < 400 && location) {
                response.resume();
                if (redirectCount >= MAX_REDIRECTS) {
                    fail(new Error('Terlalu banyak pengalihan HTTPS.'));
                    return;
                }

                let redirectUrl;
                try {
                    redirectUrl = new URL(location, targetUrl);
                    options.validateUrl(redirectUrl);
                } catch (error) {
                    fail(error);
                    return;
                }

                requestHttpsOnce(
                    redirectUrl,
                    options,
                    redirectCount + 1,
                    lookup
                ).then(resolve, reject);
                return;
            }

            if (statusCode < 200 || statusCode >= 300) {
                response.resume();
                fail(new Error(`HTTP ${statusCode}`));
                return;
            }

            const contentLength = Number(response.headers['content-length']);
            if (
                Number.isFinite(contentLength) &&
                contentLength > options.maxBytes
            ) {
                response.destroy();
                fail(new Error('Respons melebihi batas ukuran.'));
                return;
            }

            const chunks = [];
            let totalBytes = 0;

            response.on('data', chunk => {
                totalBytes += chunk.length;
                if (totalBytes > options.maxBytes) {
                    response.destroy();
                    fail(new Error('Respons melebihi batas ukuran.'));
                    return;
                }
                chunks.push(chunk);
            });

            response.on('end', () => {
                if (!settled) {
                    settled = true;
                    resolve({
                        body: Buffer.concat(chunks, totalBytes),
                        headers: response.headers,
                        url: targetUrl
                    });
                }
            });
            response.on('error', fail);
        });

        request.on('timeout', () => {
            request.destroy(new Error('Koneksi HTTPS timeout.'));
        });
        request.on('error', fail);
    });
}

async function requestHttps(url, options, redirectCount = 0) {
    try {
        return await requestHttpsOnce(url, options, redirectCount);
    } catch (error) {
        if (getNetworkErrorCode(error) === 'CERT_HAS_EXPIRED') {
            throw addCertificateGuidance(error);
        }

        if (getProxyAgent() || !shouldRetryWithDoh(error)) {
            throw error;
        }

        const targetUrl = new URL(url);
        try {
            const addresses = await resolveWithDoh(targetUrl.hostname);
            console.warn(
                '[R34] DNS langsung gagal; mencoba DNS-over-HTTPS untuk',
                targetUrl.hostname
            );
            return await requestHttpsOnce(
                targetUrl,
                options,
                redirectCount,
                createDohLookup(addresses)
            );
        } catch (fallbackError) {
            if (getNetworkErrorCode(fallbackError) === 'CERT_HAS_EXPIRED') {
                throw addCertificateGuidance(fallbackError);
            }

            throw new Error(
                `${error.message}; DNS-over-HTTPS juga gagal: ` +
                fallbackError.message,
                { cause: fallbackError }
            );
        }
    }
}

async function fetchJson(url) {
    try {
        const waitMs = Math.max(
            0,
            1000 - (Date.now() - lastApiRequestAt)
        );
        if (waitMs) {
            await new Promise(resolve => setTimeout(resolve, waitMs));
        }
        lastApiRequestAt = Date.now();

        const response = await requestHttps(url, {
            maxBytes: MAX_API_BYTES,
            timeoutMs: 20000,
            headers: {
                Accept: 'application/json'
            },
            validateUrl: redirectUrl => {
                if (
                    redirectUrl.protocol !== 'https:' ||
                    redirectUrl.hostname !== 'e621.net'
                ) {
                    throw new Error('URL pengalihan API tidak aman.');
                }
            }
        });

        let data;
        try {
            data = JSON.parse(response.body.toString('utf8'));
        } catch {
            throw new Error('Respons API bukan JSON yang valid.');
        }

        if (!data || !Array.isArray(data.posts)) {
            throw new Error('Format respons API tidak dikenali.');
        }

        return data.posts.map(post => ({
            ...post,
            file_url: post.sample?.url || post.file?.url || '',
            tags: normalizeTags(post.tags)
        }));
    } catch (error) {
        throw new Error(`Gagal mengambil hasil e621: ${error.message}`);
    }
}

function parseImageUrl(fileUrl) {
    if (typeof fileUrl !== 'string' || !fileUrl.trim()) {
        throw new Error('URL gambar e621 kosong');
    }

    const imageUrl = new URL(fileUrl, 'https://e621.net');
    if (imageUrl.protocol === 'http:') {
        imageUrl.protocol = 'https:';
    }

    if (
        imageUrl.protocol !== 'https:' ||
        !(
            imageUrl.hostname === 'e621.net' ||
            imageUrl.hostname.endsWith('.e621.net')
        )
    ) {
        throw new Error('URL gambar e621 tidak aman');
    }

    return imageUrl;
}

function isSupportedImage(post) {
    try {
        const imageUrl = parseImageUrl(post.file_url);
        return /\.(jpe?g|png|webp|gif)$/i.test(imageUrl.pathname);
    } catch {
        return false;
    }
}

function detectImageType(buffer) {
    if (
        buffer.length >= 3 &&
        buffer[0] === 0xff &&
        buffer[1] === 0xd8 &&
        buffer[2] === 0xff
    ) {
        return 'image/jpeg';
    }

    if (
        buffer.length >= 8 &&
        buffer.subarray(0, 8).equals(
            Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])
        )
    ) {
        return 'image/png';
    }

    if (
        buffer.length >= 12 &&
        buffer.toString('ascii', 0, 4) === 'RIFF' &&
        buffer.toString('ascii', 8, 12) === 'WEBP'
    ) {
        return 'image/webp';
    }

    if (
        buffer.length >= 6 &&
        ['GIF87a', 'GIF89a'].includes(buffer.toString('ascii', 0, 6))
    ) {
        return 'image/gif';
    }

    return null;
}

async function fetchImage(post) {
    const imageUrl = parseImageUrl(post.file_url);

    const response = await requestHttps(imageUrl, {
        maxBytes: MAX_IMAGE_BYTES,
        timeoutMs: 30000,
        headers: {
            'Referer': 'https://e621.net/'
        },
        validateUrl: redirectUrl => {
            parseImageUrl(redirectUrl.href);
        }
    });

    if (!isSupportedImage({ file_url: response.url.href })) {
        throw new Error('URL pengalihan gambar e621 tidak aman');
    }

    const declaredType = String(response.headers['content-type'] || '')
        .split(';')[0]
        .trim()
        .toLowerCase();
    if (
        declaredType &&
        ![
            'image/jpeg',
            'image/jpg',
            'image/png',
            'image/webp',
            'image/gif',
            'application/octet-stream'
        ].includes(declaredType)
    ) {
        throw new Error(`Tipe media tidak didukung: ${declaredType}`);
    }

    const buffer = response.body;
    const contentType = detectImageType(buffer);
    if (!contentType) {
        throw new Error('Respons e621 bukan berkas gambar yang valid');
    }

    return new MessageMedia(
        contentType,
        buffer.toString('base64'),
        `rule34-${post.id}`
    );
}

async function execute(message, args = []) {
    if (!getR18()) {
        await message.reply(
            'Fitur /r34 sedang nonaktif. Aktifkan dulu dengan /nsfw on.'
        );
        return;
    }

    const query = args.join(' ').trim();
    const caption = query
        ? `e621 | ${query}`
        : 'e621 | Acak';

    try {
        const posts = await fetchJson(buildSearchUrl(query));
        const candidates = posts.filter(post =>
            post &&
            isSupportedImage(post) &&
            !isBlocked(post.tags)
        );

        if (!candidates.length) {
            await message.reply(
                query
                    ? 'Tidak ada hasil yang lolos penyaring tag. Coba tag lain.'
                    : 'Tidak ada hasil acak yang lolos penyaring.'
            );
            return;
        }

        const shuffled = candidates
            .map(post => ({ post, order: Math.random() }))
            .sort((a, b) => a.order - b.order)
            .map(entry => entry.post);

        let lastError;
        for (const post of shuffled.slice(0, 5)) {
            try {
                const media = await fetchImage(post);
                await message.reply(media, undefined, {
                    caption
                });
                return;
            } catch (error) {
                lastError = error;
                console.warn('[R34] Gagal mengirim kandidat e621:', error.message);
            }
        }

        throw lastError || new Error('Tidak ada gambar yang dapat dikirim');
    } catch (error) {
        console.error('[R34] Gagal memproses pencarian:', error);
        await message.reply(
            `Gagal mengambil hasil e621: ${error.message}`
        );
    }
}

